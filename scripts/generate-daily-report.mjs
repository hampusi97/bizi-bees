/**
 * scripts/generate-daily-report.mjs — Dropper OS Daily Report Generator
 * Dropper OS — Phase 7
 *
 * Runs TreasuryBot against recorded store results, writes reports/LATEST.md
 * and reports/treasury-results.json. Invoked by .github/workflows/dropper-autoloop.yml
 * every day and manually via `node scripts/generate-daily-report.mjs`.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();

function loadStores() {
  const raw = readFileSync(join(ROOT, "config", "stores-15.config.json"), "utf8");
  return JSON.parse(raw).stores;
}

function loadResults() {
  const file = join(ROOT, "reports", "treasury-results.json");
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  return [];
}

function netProfit(r) {
  const processing = r.grossSales * 0.029 + 0.30;
  return r.grossSales - r.discounts - r.landedCogs - r.shipping - processing - r.adSpend;
}

function main() {
  const stores = loadStores();
  const results = loadResults();
  mkdirSync(join(ROOT, "reports"), { recursive: true });

  const totalGross = results.reduce((s, r) => s + r.grossSales, 0);
  const totalNet = results.reduce((s, r) => s + netProfit(r), 0);
  const targetDaily = stores.reduce((s, r) => s + r.dailyTargetUSD, 0);
  const pace = targetDaily > 0 ? Math.round((totalNet / targetDaily) * 100) : 0;
  const storesAtTarget = results.filter((r) => netProfit(r) >= 111.11).length;
  const b = {
    cogsFloat: Math.round(totalNet * 0.35 * 100) / 100,
    growthAds: Math.round(totalNet * 0.25 * 100) / 100,
    taxReserve: Math.round(totalNet * 0.2 * 100) / 100,
    ownerTakeHome: Math.round(totalNet * 0.2 * 100) / 100,
  };

  const today = new Date().toISOString().slice(0, 10);
  const lines = [
    "# Dropper OS — Daily Treasury Report",
    `Date: ${today}`,
    "",
    "## $50,000/Month Goal Engine",
    `- Fleet daily target: $${targetDaily.toFixed(2)} ($1,667/day = $111.11 x 15 stores)`,
    `- Fleet gross sales today: $${totalGross.toFixed(2)}`,
    `- Fleet true net profit today: $${totalNet.toFixed(2)}`,
    `- Goal pace: ${pace}% of daily target`,
    `- Stores at/above target: ${storesAtTarget} / ${stores.length}`,
    "",
    "## Profit Bucket Split",
    `- COGS Float (35%): $${b.cogsFloat.toFixed(2)}`,
    `- Growth / Ads (25%): $${b.growthAds.toFixed(2)}`,
    `- Tax Reserve (20%): $${b.taxReserve.toFixed(2)}`,
    `- Owner Take-Home (20%): $${b.ownerTakeHome.toFixed(2)}`,
    "",
    "## Per-Store Net Profit",
    ...results.map((r) => `- ${r.id} (${r.name}): net $${netProfit(r).toFixed(2)} (target $111.11/day)`),
    "",
    "---",
    "_Generated by Dropper OS TreasuryBot (Phase 7)_",
  ];

  const report = lines.join("\n");
  writeFileSync(join(ROOT, "reports", "LATEST.md"), report);
  process.stdout.write(report + "\n");
  process.stdout.write(`\n[generate-daily-report] wrote reports/LATEST.md (pace ${pace}%)\n`);
}

main();
